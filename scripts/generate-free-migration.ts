import { readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { schema } from '../packages/db/schema';
const target = new URL('../supabase/migrations/202610120001_free_hosting.sql', import.meta.url);
if (existsSync(target)) throw new Error('The initial migration already exists and must remain immutable. Create a new versioned migration for follow-up changes.');
const security = await readFile(new URL('../supabase/security.sql', import.meta.url), 'utf8');
await writeFile(target, '-- Generated by npm run db:generate:free. Do not edit this migration directly.\n' + schema + '\n' + security, { flag: 'wx' });
